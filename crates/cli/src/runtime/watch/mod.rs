//! 事件订阅面：把本机发生的事推给宿主程序。
//!
//! ## 与 `transfer watch` 的分工
//!
//! 两者并存是刻意的，判据一句话：**面板服务于「此刻我想看一眼」，订阅服务于「有变化
//! 就告诉我」**。
//!
//! | | `transfer watch` | `watch`（本模块） |
//! |---|---|---|
//! | 受众 | 人 | 程序 |
//! | 覆盖 | 只有传输 | 收件箱 / 传输 / 设备 |
//! | 形态 | 固定间隔重绘**全量快照**，带热键 | **增量推送**，一次基线之后只发变化 |
//! | 去向 | stderr（它是过程信息） | stdout（它是命令结果） |
//! | 节点起落 | 每次刷新各自判断 | 跨起落存活，节点回来自动接上 |
//!
//! ## 分工
//!
//! - [`event`]：线格式。**对外契约**，改它要按 schema 版本的判据递增版本号。
//! - [`baseline`]：整值快照。两条来源（活节点 / 本机记录）共用一份装配。
//! - [`fold`]：收敛规则（采样降频 + 设备去重）。纯逻辑，零 IO、零时钟。
//! - [`serve`]：常驻节点那一半——订阅领域事件、收敛、写进本地通道。
//! - [`client`]：订阅方那一半——跨节点起落把服务端给的片段接成一条连续的、带单调序号
//!   的流；没有节点时自己直读本机记录拼基线。
//!
//! 两半都在 `runtime/`，`cmd/watch.rs` 只剩「解析参数 → 拿一条流 → 交给渲染」。

pub mod baseline;
pub mod client;
pub mod event;
pub mod fold;
pub mod serve;
